
"""
DAY 2: Train and Evaluate Sensor Fault Classification Model
Reads the 500 samples generated by Day 1.
"""

from pathlib import Path

import joblib
import pandas as pd

from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
)

# --------------------------------------------------
# 1. File paths
# --------------------------------------------------

DAY2_DIR = Path(__file__).resolve().parent
PROJECT_DIR = DAY2_DIR.parent.parent

CSV_PATH = PROJECT_DIR / "sensor_data.csv"
MODEL_PATH = DAY2_DIR / "sensor_model.joblib"

if not CSV_PATH.exists():
    raise FileNotFoundError(
        f"{CSV_PATH} not found. Run the Day 1 generator first."
    )

# --------------------------------------------------
# 2. Load and validate dataset
# --------------------------------------------------

df = pd.read_csv(CSV_PATH)

features = [
    "temperature",
    "pressure",
    "vibration",
    "current",
    "rpm",
]

required_columns = features + ["state"]

missing = set(required_columns) - set(df.columns)

if missing:
    raise ValueError(f"Missing columns: {sorted(missing)}")

df = df[required_columns].copy()

for col in features:
    df[col] = pd.to_numeric(df[col], errors="raise")

if df[required_columns].isnull().any().any():
    raise ValueError("Dataset contains missing values.")

if not all(
    pd.api.types.is_numeric_dtype(df[col])
    for col in features
):
    raise ValueError("Sensor columns must be numeric.")

df["state"] = df["state"].astype(str).str.strip().str.upper()

if (df["state"] == "").any():
    raise ValueError("Dataset contains empty state labels.")

if len(df) < 10:
    raise ValueError("Not enough samples to train and evaluate.")

class_counts = df["state"].value_counts()

if (class_counts < 2).any():
    raise ValueError(
        "Each state must have at least two samples for a "
        "stratified train/test split.\n"
        f"Class counts:\n{class_counts}"
    )

print("=== DATASET SUMMARY ===")
print("Dataset path:", CSV_PATH)
print("Dataset shape:", df.shape)
print("\nFirst 5 rows:")
print(df.head())

print("\nClass distribution:")
print(class_counts)

# --------------------------------------------------
# 3. Separate inputs and target
# --------------------------------------------------

X = df[features]
y = df["state"]

# --------------------------------------------------
# 4. Split into training and testing sets
# --------------------------------------------------

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.25,
    random_state=42,
    stratify=y,
)

print("\n=== DATA SPLIT ===")
print("Training samples:", len(X_train))
print("Testing samples:", len(X_test))

# --------------------------------------------------
# 5. Train Random Forest
# --------------------------------------------------

model = RandomForestClassifier(
    n_estimators=200,
    class_weight="balanced",
    random_state=42,
    n_jobs=-1,
)

model.fit(X_train, y_train)

print("\nModel training completed!")

# --------------------------------------------------
# 6. Evaluate model
# --------------------------------------------------

y_pred = model.predict(X_test)

accuracy = accuracy_score(y_test, y_pred)

print("\n=== MODEL EVALUATION ===")
print(f"Accuracy: {accuracy:.4f} ({accuracy:.2%})")

print("\nClassification report:")
print(
    classification_report(
        y_test,
        y_pred,
        labels=model.classes_,
        zero_division=0,
    )
)

print("\nConfusion matrix:")
print("Class order:", list(model.classes_))
print(
    confusion_matrix(
        y_test,
        y_pred,
        labels=model.classes_,
    )
)

# --------------------------------------------------
# 7. Feature importance
# --------------------------------------------------

importance = pd.Series(
    model.feature_importances_,
    index=features,
).sort_values(ascending=False)

print("\n=== FEATURE IMPORTANCE ===")
print(importance.to_string())

# --------------------------------------------------
# 8. Save trained model
# --------------------------------------------------

joblib.dump(model, MODEL_PATH)

print(f"\nTrained model saved to: {MODEL_PATH}")

# --------------------------------------------------
# 9. Demonstrate prediction
# --------------------------------------------------

new_reading = pd.DataFrame([{
    "temperature": 95.0,
    "pressure": 4.8,
    "vibration": 2.5,
    "current": 12.0,
    "rpm": 1800,
}])

predicted_state = model.predict(new_reading)[0]
probabilities = model.predict_proba(new_reading)[0]

print("\n=== NEW SENSOR PREDICTION ===")
print(new_reading.to_string(index=False))
print("Predicted state:", predicted_state)

print("\nClass probabilities:")
for state, probability in zip(model.classes_, probabilities):
    print(f"{state}: {probability:.2%}")
